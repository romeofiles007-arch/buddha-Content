/** หมวดจากชื่อหมวด/รหัส ('buddha' | 'หมวด 1 · …' | 'พระเกจิ…') — ไม่รู้จัก = null */
export function categoryOf(value) {
  const v = String(value ?? '').trim()
  if (!v || v === 'mix') return null
  return CATEGORIES.find((c) => c.id === v || c.name === v || v.includes(c.name.replace(/^หมวด \d · /, '')) || c.name.includes(v)) ?? null
}

