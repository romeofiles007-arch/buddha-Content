/** ชื่อในรายการที่ข้อความพูดถึง — ใช้อ่านคอลัมน์ Theme ที่ ChatGPT ตอบกลับ */
const findIn = (list, text) => list.find((x) => String(text ?? '').includes(x.split(' (')[0])) ?? null

/** คอลัมน์ Theme ("ด้านชีวิต / หลักธรรม") → { area, dhamma } ตามชื่อในรายการ */
export function parseTheme(text) {
  return { area: findIn(LIFE_AREAS.map((a) => a.name), text), dhamma: findIn(DHAMMA_POINTS, text) }
}

/**
 * สุ่มคู่ ด้านชีวิต + หลักธรรม n คู่ ไม่ซ้ำกันเอง และเลี่ยงของคลิปล่าสุด (recent = [{ area, dhamma }])
 * เลี่ยงแล้วเหลือไม่พอ → เติมจากของที่เพิ่งใช้ (เก่าสุดก่อน)
 */
export function pickThemes(n = 5, recent = []) {
  const take = (all, used) => {
    const usedSet = new Set(used.filter(Boolean))
    const fresh = shuffle(all.filter((x) => !usedSet.has(x)))
    const stale = [...used.filter(Boolean)].reverse().filter((x, i, a) => all.includes(x) && a.indexOf(x) === i)
    return [...fresh, ...stale].slice(0, n)
  }
  const areas = take(LIFE_AREAS.map((a) => a.name), recent.map((r) => r.area))
  const dhammas = take(DHAMMA_POINTS, recent.map((r) => r.dhamma))
  return areas.map((area, i) => ({ area, dhamma: dhammas[i] }))
}

