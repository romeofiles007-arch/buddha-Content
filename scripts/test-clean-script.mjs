// เทสต์: cleanScript ตัดหัวข้อที่ ChatGPT แถมมาบนสุดของบท — ไม่ให้ไปโผล่ในเสียงพากย์/ซับ
//   node scripts/test-clean-script.mjs
// เคยเป็น: คลิป "การให้อภัยตัวเอง" มีซับ "บทพากย์ 1 นาที — การให้อภัยตัวเอง" ตอนเปิดคลิป
// (ChatGPT ใส่หัวข้อ markdown แต่แผงอ่านข้อความที่แสดงบนจอ เครื่องหมาย # หายไป เหลือเป็นบรรทัดธรรมดา)
import assert from 'node:assert/strict'
import { cleanScript } from '../extension/prompts.js'

let passed = 0
const test = (name, fn) => {
  fn()
  passed++
  console.log(`  ✓ ${name}`)
}

const BODY = 'เคยไหมครับ ที่เราให้อภัยคนอื่นได้\nแต่กลับให้อภัยตัวเองไม่ได้'

test('ตัดหัวข้อ "บทพากย์ 1 นาที — ชื่อเรื่อง" บนสุด (เคสจริง)', () => {
  assert.equal(cleanScript(`บทพากย์ 1 นาที — การให้อภัยตัวเอง\n\n${BODY}`), BODY)
})

test('ตัดป้ายแบบอื่นที่ ChatGPT ชอบใส่: สคริปต์ / บทบรรยาย / Narration / 旁白 / ความยาว', () => {
  for (const head of [
    'บทพากย์:', 'บทพากย์ (ประมาณ 1 นาที)', 'บทพากย์ภาษาไทย – ปล่อยวาง', 'สคริปต์: ปล่อยวาง', 'บทบรรยาย 5 นาที',
    'Narration:', 'Script — Letting go', 'Voice-over (1 min)', '旁白：', '解说词（1分钟）',
    'ความยาวประมาณ 1 นาที', 'ชื่อเรื่อง: การให้อภัยตัวเอง',
  ]) assert.equal(cleanScript(`${head}\n${BODY}`), BODY, head)
  assert.equal(cleanScript(`บทพากย์ 1 นาที — การให้อภัยตัวเอง\nความยาวประมาณ 1 นาที\n\n${BODY}`), BODY, 'หลายบรรทัดติดกันบนสุด')
})

test('ตัดหมายเหตุท้ายบทที่ ChatGPT แถมหลังสั่งปรับความยาว (เคสจริง "ตัดให้กระชับ ครบหนึ่งนาที")', () => {
  assert.equal(cleanScript(`${BODY}\nตัดให้กระชับ ครบหนึ่งนาที`), BODY)
  assert.equal(cleanScript(`${BODY}\n\nตัดให้กระชับ\nครบหนึ่งนาที`), BODY, 'แยกสองบรรทัด')
  for (const tail of [
    'ตัดให้สั้นลงแล้วครับ', 'ปรับให้ยาวขึ้นตามเป้าแล้ว', 'ความยาวประมาณ 1 นาที', 'ประมาณ 1.5 นาที', 'รวม 812 ตัวอักษร',
    'หากต้องการให้ปรับเพิ่ม บอกได้เลยครับ', 'ถ้าต้องการเวอร์ชันสั้นกว่านี้ แจ้งได้ครับ', 'Word count: 150', 'Let me know if you want changes.', '字数：约300字',
  ]) assert.equal(cleanScript(`${BODY}\n${tail}`), BODY, tail)
})

test('ตัดหมายเหตุบนสุดแบบ "ตัดให้สั้นลงแล้ว:" ด้วย', () => {
  assert.equal(cleanScript(`ตัดให้สั้นลงแล้วครับ:\n${BODY}`), BODY)
})

test('ไม่แตะบรรทัดในเนื้อเรื่อง แม้มีคำว่า "บทพากย์" หรือ "นาที"', () => {
  const story = `${BODY}\nบทพากย์นี้ขอฝากไว้ให้คิด\nเพียงหนึ่งนาทีที่หยุดใจ ก็พอแล้วครับ`
  assert.equal(cleanScript(story), story)
  assert.equal(cleanScript('สคริปต์ชีวิตของเรา เขียนใหม่ได้เสมอ\nขอเพียงเริ่มวันนี้'), 'สคริปต์ชีวิตของเรา เขียนใหม่ได้เสมอ\nขอเพียงเริ่มวันนี้')
  // ประโยคปิดจริงที่พูดถึงเวลา/การตัด ต้องอยู่ครบ
  for (const end of ['เพียงหนึ่งนาทีที่หยุดใจ ก็พอแล้วครับ', 'ตัดความโกรธทิ้งไป ใจก็เบาลง', 'ขอให้ทุกท่านมีความสุขครับ']) assert.equal(cleanScript(`${BODY}\n${end}`), `${BODY}\n${end}`, end)
})

test('ของเดิมยังทำงาน: # หัวข้อ · bullet · [visual] · (stage) · **ตัวหนา** · code block', () => {
  assert.equal(cleanScript('```\n# หัวข้อ\n- ข้อ\n[ภาพวัด]\n(หยุด)\n**เคยไหมครับ**\n```'), 'เคยไหมครับ')
})

console.log(`\nผ่าน ${passed} ข้อ`)
